#include <iostream>
#include <vector>
using namespace std;

class A {
int x;
 public:
	A(int e) {x=e; cout << "in constructor:" << e << "\n";}
	A(const A &a) {cout << "copy constructor called " << a.x << endl; x = a.x*100;}
	void f() {cout << x << endl;}

};

int main () {

vector<A> avec;

	A a1(10), a2(20), a3(30);
	int i=0;
	cout << avec.capacity() << endl;
	avec.push_back(a1);
	cout << avec.capacity() << endl;
	avec.push_back(a2);
	cout << avec.capacity() << endl;
	avec.push_back(a3);
	cout << avec.capacity() << endl;
	
	for (auto &x : avec) {
		x.f() ;
	}
}

// The old elements are copied to the new vector when the capacity is reached.
// Since we've defined a copy constructor, it is called when the old elements are
// copied and move() is not generated by the compiler.